-- 1. Helper function to read agency_id from Node.js backend session
CREATE OR REPLACE FUNCTION get_current_agency_id() RETURNS integer AS $$
  SELECT NULLIF(current_setting('app.current_agency_id', true), '')::integer;
$$ LANGUAGE sql STABLE;

